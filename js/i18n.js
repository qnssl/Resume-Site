const RU_TITLE = document.title;
const metaDesc = document.querySelector('meta[name="description"]');
const RU_DESC = metaDesc ? metaDesc.content : "";
let LANG = "ru";
try {
  const saved = localStorage.getItem("lang");
  if (saved === "ru" || saved === "en") LANG = saved;
  else if (!/^(ru|be|uk)/i.test(navigator.language || "ru")) LANG = "en";
} catch (error) {
  /* Language switching still works when storage is disabled. */
}

const t = (key) => I18N[LANG][key] ?? key;

function applyLang(lang) {
  LANG = lang;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    if (node.dataset.ru === undefined) node.dataset.ru = node.textContent;
    const text = lang === "en" ? I18N.en[node.dataset.i18n] : node.dataset.ru;
    if (text !== undefined) node.textContent = text;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    if (node.dataset.ruAria === undefined) node.dataset.ruAria = node.getAttribute("aria-label");
    const label = lang === "en" ? I18N.en[node.dataset.i18nAria] : node.dataset.ruAria;
    if (label !== undefined) node.setAttribute("aria-label", label);
  });
  document.title = lang === "en" ? I18N.en.title : RU_TITLE;
  if (metaDesc) metaDesc.content = lang === "en" ? I18N.en.desc : RU_DESC;
  const button = document.getElementById("lang-btn");
  button.textContent = lang === "ru" ? "EN" : "RU";
  button.setAttribute("lang", lang === "ru" ? "en" : "ru");
  button.setAttribute("aria-label", lang === "ru" ? "Switch to English" : "Переключить на русский");
  try {
    localStorage.setItem("lang", lang);
  } catch (error) {
    /* Storage is optional. */
  }
  document.dispatchEvent(new CustomEvent("langchange"));
}

document
    .getElementById("lang-btn")
    .addEventListener("click", () => applyLang(LANG === "ru" ? "en" : "ru"));
applyLang(LANG);